"""Ninja build file generator for ebuild.

Generates build.ninja and compile_commands.json from a ProjectConfig.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional


@dataclass
class PackagePaths:
    """Resolved paths for an installed package (headers, libs)."""

    include_dirs: List[Path] = field(default_factory=list)
    lib_dirs: List[Path] = field(default_factory=list)
    libraries: List[str] = field(default_factory=list)


# Flags that already request position-independent code. If one of these is
# present (or explicitly disabled with -fno-*) we must not add -fPIC again.
_PIC_FLAGS = {"-fPIC", "-fpic", "-fPIE", "-fpie", "-fno-pic", "-fno-PIC",
              "-fno-pie", "-fno-PIE"}


class NinjaBackend:
    """Generate build.ninja from a ProjectConfig and resolved toolchain.

    Args:
        config: The ProjectConfig describing targets and dependencies.
        build_dir: Output directory for build artifacts.
        toolchain: A ResolvedToolchain with compiler paths.
        package_paths: Optional dict of package name → PackagePaths.
    """

    def __init__(
        self,
        config,
        build_dir: Path,
        toolchain,
        package_paths: Optional[Dict[str, PackagePaths]] = None,
    ) -> None:
        self.config = config
        self.build_dir = build_dir
        self.toolchain = toolchain
        self.package_paths = package_paths or {}

    def generate(self) -> None:
        """Generate build.ninja and compile_commands.json."""
        self.build_dir.mkdir(parents=True, exist_ok=True)
        self._write_ninja()
        self._write_compile_commands()

    def _get_toolchain_cflags(self) -> List[str]:
        """Return toolchain-level cflags including sysroot.

        Extracted to avoid duplicating sysroot/cflags logic across
        _write_ninja() and _write_compile_commands().
        """
        cflags = list(getattr(self.toolchain, "cflags", []))
        sysroot = getattr(self.toolchain, "sysroot", None)
        if sysroot:
            cflags.append(f"--sysroot={sysroot}")
        return cflags

    def _get_toolchain_ldflags(self) -> List[str]:
        """Return toolchain-level ldflags including sysroot."""
        ldflags = list(getattr(self.toolchain, "ldflags", []))
        sysroot = getattr(self.toolchain, "sysroot", None)
        if sysroot:
            ldflags.append(f"--sysroot={sysroot}")
        return ldflags

    def _resolve_target_cflags(self, target) -> List[str]:
        """Resolve all cflags for a target (toolchain + target + packages).

        Combines toolchain flags, target-specific flags, include paths,
        defines, and package include directories into a single list.

        Args:
            target: A TargetConfig with cflags, includes, defines, and uses.

        Returns:
            Combined list of compiler flags for this target.
        """
        cflags = self._get_toolchain_cflags() + list(target.cflags)
        for inc in target.includes:
            cflags.append(f"-I{inc}")
        for define in target.defines:
            cflags.append(f"-D{define}")

        for pkg_name in target.uses:
            pkg = self.package_paths.get(pkg_name)
            if pkg:
                for inc_dir in pkg.include_dirs:
                    cflags.append(f"-I{inc_dir}")

        return cflags

    def _write_ninja(self) -> None:
        """Write the build.ninja file."""
        ninja_path = self.build_dir / "build.ninja"
        lines = [
            f"# Generated by ebuild",
            f"cc = {self.toolchain.cc}",
            f"cxx = {self.toolchain.cxx}",
            f"ar = {self.toolchain.ar}",
            "",
            "rule cc",
            "  command = $cc $cflags -MMD -MF $out.d -c $in -o $out",
            "  description = CC $out",
            "  depfile = $out.d",
            "  deps = gcc",
            "",
            "rule link",
            "  command = $cc $ldflags $in -o $out $libs",
            "  description = LINK $out",
            "",
            "rule ar_rule",
            "  command = $ar rcs $out $in",
            "  description = AR $out",
            "",
        ]

        # The flag that turns a link into a shared object is spelled
        # differently on Darwin. Emit the rule only when something needs it,
        # so a purely static project's build.ninja does not carry a rule for
        # a link it never performs.
        shared_flag = "-dynamiclib" if sys.platform == "darwin" else "-shared"
        if any(t.target_type == "shared_library" for t in self.config.targets):
            lines += [
                "rule link_shared",
                f"  command = $cc {shared_flag} $ldflags $in -o $out $libs",
                "  description = LINK_SHARED $out",
                "",
            ]

        toolchain_ldflags = self._get_toolchain_ldflags()

        for target in self.config.targets:
            cflags = self._resolve_target_cflags(target)

            obj_files = []
            for src in target.sources:
                obj = str(self._object_path(target, src))
                obj_files.append(obj)
                lines.append(
                    f"build {obj}: cc {src}"
                )
                if cflags:
                    lines.append(f"  cflags = {' '.join(cflags)}")
                lines.append("")

            if target.target_type == "executable":
                ldflags = toolchain_ldflags + list(target.ldflags)
                libs = []
                dep_archives = []
                for pkg_name in target.uses:
                    pkg = self.package_paths.get(pkg_name)
                    if pkg:
                        for lib_dir in pkg.lib_dirs:
                            ldflags.append(f"-L{lib_dir}")
                        for lib in pkg.libraries:
                            libs.append(f"-l{lib}")

                # Add internal library dependencies (static_library targets)
                for dep_name in target.depends:
                    for dep_target in self.config.targets:
                        if dep_target.name == dep_name and dep_target.target_type == "static_library":
                            dep_archives.append(str(self.build_dir / f"lib{dep_name}.a"))

                link_inputs = obj_files + dep_archives
                out = str(self.build_dir / target.name)
                lines.append(
                    f"build {out}: link {' '.join(link_inputs)}"
                )
                if ldflags:
                    lines.append(f"  ldflags = {' '.join(ldflags)}")
                if libs:
                    lines.append(f"  libs = {' '.join(libs)}")
            elif target.target_type in ("static_library", "shared_library"):
                if target.target_type == "static_library":
                    ext = ".a"
                elif sys.platform == "win32":
                    ext = ".dll"
                elif sys.platform == "darwin":
                    ext = ".dylib"
                else:
                    ext = ".so"
                out = str(self.build_dir / f"lib{target.name}{ext}")

                if target.target_type == "static_library":
                    lines.append(f"build {out}: ar_rule {' '.join(obj_files)}")
                else:
                    # link_shared carries the platform's "build a shared
                    # object" flag; the -L/-l wiring is the same as for
                    # executables and still goes through ldflags/libs.
                    ldflags = list(target.ldflags)
                    libs = []
                    for pkg_name in target.uses:
                        pkg = self.package_paths.get(pkg_name)
                        if pkg:
                            for lib_dir in pkg.lib_dirs:
                                ldflags.append(f"-L{lib_dir}")
                            for lib in pkg.libraries:
                                libs.append(f"-l{lib}")

                    lines.append(f"build {out}: link_shared {' '.join(obj_files)}")
                    if ldflags:
                        lines.append(f"  ldflags = {' '.join(ldflags)}")
                    if libs:
                        lines.append(f"  libs = {' '.join(libs)}")

            lines.append("")

        ninja_path.write_text("\n".join(lines), encoding="utf-8")

    def _write_compile_commands(self) -> None:
        """Write compile_commands.json for IDE integration."""
        commands = []
        source_dir = str(self.config.source_dir.resolve())

        for target in self.config.targets:
            cflags = self._resolve_target_cflags(target)

            flags_str = f" {' '.join(cflags)}" if cflags else ""
            for src in target.sources:
                # A source shared by two targets yields two entries, which the
                # compilation database format allows. The -o keeps them
                # distinguishable, and matches what ninja actually runs.
                obj = self._object_path(target, src)
                commands.append({
                    "directory": source_dir,
                    "command": f"{self.toolchain.cc}{flags_str} -c {src} -o {obj}",
                    "file": src,
                })

        cc_path = self.build_dir / "compile_commands.json"
        cc_path.write_text(json.dumps(commands, indent=2), encoding="utf-8")
